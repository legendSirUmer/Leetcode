from typing import List
class Solution:
    def isValidSudoku(self, board: List[List[str]]) -> bool:
        answer = True
        i,j=0,0
        for a in range(9):
            row = []
            col = []
            if(i == 0 or i == 3 or i ==  6 ):
                grid1 = []
                grid2 = []
                grid3 = []
            for b in range(9):
                if(board[i][j] != '.'):
                    row.append(board[i][j])
                    if(j < 3):
                        grid1.append(board[i][j])
                    elif(j < 6):
                        grid2.append(board[i][j])
                    elif(j < 9):
                        grid3.append(board[i][j])


                if(board[j][i] != '.'):
                    col.append(board[j][i]) 
                j+=1
            i+=1
            j=0
            
            if(len(row) != len(set(row)) or  len(col) != len(set(col)) or len(grid1) != len(set(grid1)) or len(grid2) != len(set(grid2)) or len(grid3) != len(set(grid3))):
                answer = False
                return answer
        return answer
        

            
            

